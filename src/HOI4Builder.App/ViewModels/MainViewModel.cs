using System.IO;
using System.Collections.ObjectModel;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using HOI4Builder.Core.Focuses;
using HOI4Builder.Core.Projects;
using HOI4Builder.Core.Script;

namespace HOI4Builder.App.ViewModels;

public partial class MainViewModel : ViewModelBase
{
    public ObservableCollection<EditorEntry> Editors { get; } = new();

    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(HasProject))]
    [NotifyPropertyChangedFor(nameof(ShowStartScreen))]
    [NotifyPropertyChangedFor(nameof(WindowTitle))]
    [NotifyPropertyChangedFor(nameof(HasUnsavedChanges))]
    private ModProject? _project;

    [ObservableProperty]
    private EditorEntry? _selectedEditor;

    [ObservableProperty]
    private string _statusText = "No project open";

    public bool HasProject => Project != null;
    public bool HasUnsavedChanges =>
        Project != null && (Project.History.IsDirty || Project.FilePath == null);
    
    public string WindowTitle => Project is null
        ? "IronBuilder"
        : $"{Project.Name}{(HasUnsavedChanges ? " *" : "")} - IronBuilder";

    public void Save(string path)
    {
        if (Project is null)
            return;
    
        ProjectFile.Save(Project, path);
        Project.History.MarkSaved();
        StatusText = $"Saved {Path.GetFileName(path)}";
    }

    public bool ShowStartScreen => Project == null;

    // Generated by the toolkit: runs whenever Project is assigned.
    partial void OnProjectChanged(ModProject? oldValue, ModProject? newValue)
    {
        if (oldValue != null)
            oldValue.History.Changed -= OnHistoryChanged;

        Editors.Clear();

        if (newValue != null)
        {
            newValue.History.Changed += OnHistoryChanged;

            Editors.Add(new("Focus trees", new FocusEditorViewModel(newValue)));
            Editors.Add(new("Countries", new PlaceholderEditorViewModel("Countries")));
            Editors.Add(new("Characters", new PlaceholderEditorViewModel("Characters")));
            Editors.Add(new("Events", new PlaceholderEditorViewModel("Events")));
            Editors.Add(new("Decisions", new PlaceholderEditorViewModel("Decisions")));
            Editors.Add(new("National spirits", new PlaceholderEditorViewModel("National spirits")));
            Editors.Add(new("Units", new PlaceholderEditorViewModel("Units")));
            Editors.Add(new("Bookmarks", new PlaceholderEditorViewModel("Bookmarks")));

            SelectedEditor = Editors[0];
            StatusText = "Ready";
        }
        else
        {
            SelectedEditor = null;
            StatusText = "No project open";
        }

        UndoCommand.NotifyCanExecuteChanged();
        RedoCommand.NotifyCanExecuteChanged();
    }

    [RelayCommand]
    private void LoadSampleProject() => Project = CreateDemoProject();

    [RelayCommand]
    private void CloseProject() => Project = null;

    [RelayCommand(CanExecute = nameof(CanUndo))]
    private void Undo() => Project?.History.Undo();

    private bool CanUndo() => Project?.History.CanUndo == true;

    [RelayCommand(CanExecute = nameof(CanRedo))]
    private void Redo() => Project?.History.Redo();

    private bool CanRedo() => Project?.History.CanRedo == true;

    private void OnHistoryChanged()
    {
        UndoCommand.NotifyCanExecuteChanged();
        RedoCommand.NotifyCanExecuteChanged();
        StatusText = Project?.History.UndoDescription is { } next ? $"Next undo: {next}" : "Ready";

        OnPropertyChanged(nameof(HasUnsavedChanges));
        OnPropertyChanged(nameof(WindowTitle));
    }

    private static ModProject CreateDemoProject()
    {
        const string sample = """
            focus_tree = {
                id = demo
                focus = { id = DEMO_start x = 2 y = 0 }
                focus = { id = DEMO_left x = 1 y = 1 prerequisite = { focus = DEMO_start } mutually_exclusive = { focus = DEMO_right } }
                focus = { id = DEMO_right x = 3 y = 1 prerequisite = { focus = DEMO_start } mutually_exclusive = { focus = DEMO_left } }
                focus = { id = DEMO_join x = 0 y = 2 relative_position_id = DEMO_right prerequisite = { focus = DEMO_left focus = DEMO_right } }
            }
            """;

        var project = new ModProject();
        project.FocusTrees.AddRange(FocusTreeMapper.ReadTrees(PdxParser.Parse(sample)));
        return project;
    }
}