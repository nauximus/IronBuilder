using System;
using System.Collections.Generic;
using System.Linq;
using System.IO;
using HOI4Builder.App.ViewModels.Navigation;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using HOI4Builder.Core.Focuses;
using HOI4Builder.Core.Projects;
using HOI4Builder.Core.Script;
using System.ComponentModel.DataAnnotations;

namespace HOI4Builder.App.ViewModels;

public partial class MainViewModel : ViewModelBase
{
    
    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(HasProject))]
    [NotifyPropertyChangedFor(nameof(WindowTitle))]
    [NotifyPropertyChangedFor(nameof(HasUnsavedChanges))]
    [NotifyPropertyChangedFor(nameof(ModTitle))]
    [NotifyPropertyChangedFor(nameof(SaveStatusText))]

    private ModProject? _project;

    [ObservableProperty]
    private IReadOnlyList<NavMode> _modes = Array.Empty<NavMode>();

    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(IsModEditorsActive))]
    [NotifyPropertyChangedFor(nameof(IsBuildersActive))]
    private NavMode? _selectedMode;

    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(ShowStartScreen))]
    private NavPage? _selectedPage;
    private readonly Dictionary<NavMode, NavPage> _lastPageByMode = new();

    public string ModTitle => Project?.Name ?? "No Project open";
    public string SaveStatusText =>
        Project is null ? ""
        : Project.FilePath is null ? "Not saved yet"
        : HasUnsavedChanges ? "Unsaved changes"
        : "All changes saved";

    public bool IsModEditorsActive => Modes.Count > 0 && SelectedMode == Modes[0];
    public bool IsBuildersActive => Modes.Count > 1 && SelectedMode == Modes[1];

    [ObservableProperty]
    private string _statusText = "No project open";

    [ObservableProperty]
    private CountrySelection? _selection;

    public bool HasProject => Project != null;
    public bool HasUnsavedChanges =>
        Project != null && (Project.History.IsDirty || Project.FilePath == null);
    
    public string WindowTitle => Project is null
        ? "IronBuilder"
        : $"{Project.Name}{(HasUnsavedChanges ? " *" : "")} - IronBuilder";

    public void Save(string path)
    {
        if (Project is null)
            return;
    
        ProjectFile.Save(Project, path);
        Project.History.MarkSaved();
        StatusText = $"Saved {Path.GetFileName(path)}";

        OnPropertyChanged(nameof(HasUnsavedChanges));
        OnPropertyChanged(nameof(WindowTitle));
        OnPropertyChanged(nameof(SaveStatusText));
    }

    public bool ShowStartScreen => Project == null && (SelectedPage is null || SelectedPage.Id == "overview");

    public MainViewModel()
    {
        Modes = NavigationCatalog.Build(null, null);
        SelectedMode = Modes[0];
    }

    // Generated by the toolkit: runs whenever Project is assigned.
        partial void OnProjectChanged(ModProject? oldValue, ModProject? newValue)
    {
        if (oldValue != null)
            oldValue.History.Changed -= OnHistoryChanged;

        _lastPageByMode.Clear();

        if (newValue != null)
        {
            newValue.History.Changed += OnHistoryChanged;
            Selection = new CountrySelection(newValue);

            Modes = NavigationCatalog.Build(newValue, Selection);
            SelectedMode = Modes[0];

            SelectedPage = Modes
                .SelectMany(m => m.Sections)
                .SelectMany(s => s.Pages)
                .First(p => p.Id == "overview");

            StatusText = "Ready";
        }
        else
        {
            Selection = null;
            Modes = NavigationCatalog.Build(null, null);
            SelectedMode = Modes[0];
            StatusText = "No project open";
        }

        UndoCommand.NotifyCanExecuteChanged();
        RedoCommand.NotifyCanExecuteChanged();

        OnPropertyChanged(nameof(SaveStatusText));
    }

        [RelayCommand]
    private void SelectMode(NavMode mode) => SelectedMode = mode;

    [RelayCommand]
    private void SelectPage(NavPage page)
    {
        if (!page.IsEnabled)
            return;
        
        SelectedPage = page;
    }

    partial void OnSelectedModeChanged(NavMode? oldValue, NavMode? newValue)
    {
        if (newValue is null)
        {
            SelectedPage = null;
            return;
        }

        SelectedPage = _lastPageByMode.TryGetValue(newValue, out var last)
            ? last
            : newValue.Sections.SelectMany(s => s.Pages).FirstOrDefault();
    }

    partial void OnSelectedPageChanged(NavPage? oldValue, NavPage? newValue)
    {
        if (oldValue != null)
            oldValue.IsSelected = false;

        if (newValue != null)
        {
            newValue.IsSelected = true;

            if (SelectedMode != null)
                _lastPageByMode[SelectedMode] = newValue;
        }
    }

    [RelayCommand]
    private void LoadSampleProject() => Project = CreateDemoProject();

    [RelayCommand]
    private void CloseProject() => Project = null;

    [RelayCommand(CanExecute = nameof(CanUndo))]
    private void Undo() => Project?.History.Undo();

    private bool CanUndo() => Project?.History.CanUndo == true;

    [RelayCommand(CanExecute = nameof(CanRedo))]
    private void Redo() => Project?.History.Redo();

    private bool CanRedo() => Project?.History.CanRedo == true;

    private void OnHistoryChanged()
    {
        UndoCommand.NotifyCanExecuteChanged();
        RedoCommand.NotifyCanExecuteChanged();
        StatusText = Project?.History.UndoDescription is { } next ? $"Next undo: {next}" : "Ready";

        OnPropertyChanged(nameof(HasUnsavedChanges));
        OnPropertyChanged(nameof(WindowTitle));
    }

    private static ModProject CreateDemoProject()
    {
        const string sample = """
            focus_tree = {
                id = demo
                country = { factor = 0 modifier = { add = 10 tag = DEM }}
                focus = { id = DEMO_start x = 2 y = 0 }
                focus = { id = DEMO_left x = 1 y = 1 prerequisite = { focus = DEMO_start } mutually_exclusive = { focus = DEMO_right } }
                focus = { id = DEMO_right x = 3 y = 1 prerequisite = { focus = DEMO_start } mutually_exclusive = { focus = DEMO_left } }
                focus = { id = DEMO_join x = 0 y = 2 relative_position_id = DEMO_right prerequisite = { focus = DEMO_left focus = DEMO_right } }
            }
            """;

        var project = new ModProject();
        project.FocusTrees.AddRange(FocusTreeMapper.ReadTrees(PdxParser.Parse(sample)));
        project.EnsureCountriesForTrees();
        return project;
    }
}